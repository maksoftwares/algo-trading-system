def compile_ea(backtest_root: Path, metaeditor: Path) -> Path:
    experts = backtest_root / "MQL5" / "Experts"
    experts.mkdir(parents=True, exist_ok=True)
    target = experts / f"{EA_NAME}.mq5"
    shutil.copy2(EA_SOURCE, target)
    log = backtest_root / "Logs" / f"compile_{EA_NAME}_variants_20260701.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [str(metaeditor), f"/compile:{target}", f"/log:{log}"],
        text=True,
        capture_output=True,
        timeout=120,
        check=False,
    )
    ex5 = experts / f"{EA_NAME}.ex5"
    if not ex5.exists():
        raise RuntimeError(f"MetaEditor did not produce EX5. Log:\n{read_text(log)}")
    log_text = read_text(log).lower()
    if "error(s)" in log_text and "0 error(s)" not in log_text:
        raise RuntimeError(f"MetaEditor compile reported errors:\n{read_text(log)}")
    return log


def run_variant(
    backtest_root: Path,
    terminal: Path,
    variant: Variant,
    variant_dir: Path,
    from_date: str,
    to_date: str,
    tag: str,
    timeout_seconds: int,
    deposit: str,
    currency: str,
) -> dict[str, Any]:
    report_base = f"A1XauM5Momentum_{tag}_XAUUSD_M5_{variant.name}"
    startup_log = f"a1_xau_m5_momentum_{variant.name}_startup_log.csv"
    signal_log = f"a1_xau_m5_momentum_{variant.name}_signal_log.csv"
    order_log = f"a1_xau_m5_momentum_{variant.name}_order_log.csv"
    management_log = f"a1_xau_m5_momentum_{variant.name}_management_log.csv"
    remove_old_variant_files(backtest_root, report_base, startup_log, signal_log, order_log, management_log)
    config = write_config(
        backtest_root,
        variant,
        report_base,
        startup_log,
        signal_log,
        order_log,
        management_log,
        from_date,
        to_date,
        tag,
        deposit=deposit,
        currency=currency,
    )

    started = datetime.now(timezone.utc)
    process = subprocess.Popen(
        [str(terminal), "/portable", f"/config:{config}"],
        cwd=str(backtest_root),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    try:
        process.wait(timeout=timeout_seconds)
    except subprocess.TimeoutExpired:
        process.terminate()
        try:
            process.wait(timeout=20)
        except subprocess.TimeoutExpired:
            process.kill()
        raise RuntimeError(f"Timed out waiting for MT5 tester variant {variant.name}.")

    elapsed_seconds = round((datetime.now(timezone.utc) - started).total_seconds(), 2)
    html_report = backtest_root / "Reports" / f"{report_base}.htm"
    if not html_report.exists():
        raise RuntimeError(f"Missing MT5 report for {variant.name}: {html_report}")

    trades, metrics = parse_mt5_report(html_report)
    bars = int(re.sub(r"[^0-9]", "", str(metrics.get("Bars", "0"))) or "0")
    ticks = int(re.sub(r"[^0-9]", "", str(metrics.get("Ticks", "0"))) or "0")
    if bars <= 0 or ticks <= 0:
        raise RuntimeError(
            "MT5 tester returned zero bars/ticks for "
            f"{variant.name} ({from_date}->{to_date}, currency={currency}). "
            "This is a tester/data failure, not a strategy result. "
            "For multi-year Capital.com tests, use USD currency unless conversion history is available."
        )
    order_rows = read_order_rows(backtest_root, order_log)
    summary = summarize_trades(trades)
    copied_html = variant_dir / f"{report_base}.htm"
    copied_csv = variant_dir / f"{report_base}_trades.csv"
    copied_order_csv = variant_dir / f"{report_base}_orders.csv"
    copied_signal_csv = variant_dir / f"{report_base}_signals.csv"
    copied_management_csv = variant_dir / f"{report_base}_management.csv"
    copied_json = variant_dir / f"{report_base}_summary.json"
    shutil.copy2(html_report, copied_html)
    write_trades(copied_csv, trades)
    copy_tester_file(backtest_root, order_log, copied_order_csv)
    copy_tester_file(backtest_root, signal_log, copied_signal_csv)
    copy_tester_file(backtest_root, management_log, copied_management_csv)

    order_actions = Counter(row.get("action", "") for row in order_rows)
    guard_reasons = Counter((row.get("reason") or "pass") for row in order_rows)
    result = {
        "name": variant.name,
        "label": variant.label,
        "run_id": variant.run_id,
        "elapsed_seconds": elapsed_seconds,
        "tester_config": str(config),
        "html_report": str(copied_html),
        "trade_csv": str(copied_csv),
        "order_csv": str(copied_order_csv),
        "signal_csv": str(copied_signal_csv),
        "management_csv": str(copied_management_csv),
        "summary_json": str(copied_json),
        "mt5_report_metrics": metrics,
        "summary": summary,
        "order_activity": {
            "rows": len(order_rows),
            "actions": dict(order_actions),
            "guard_reasons": dict(guard_reasons),
        },
    }
    copied_json.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


